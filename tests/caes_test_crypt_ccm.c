/* Tests AES-CCM de/encryption
 * Returns 1 if successful or -1 on error
 */
int caes_test_crypt_ccm_ctr_only(
     int mode,
     const uint8_t *key,
     size_t key_bit_size,
     const uint8_t *nonce,
     size_t nonce_size,
     const uint8_t *input_data,
     size_t input_data_size,
     const uint8_t *expected_output_data,
     size_t expected_output_data_size )
{
	uint8_t output_data[ 256 ];

	libcaes_context_t *context = NULL;
	libcerror_error_t *error   = NULL;
	static char *function      = "caes_test_crypt_ccm_ctr_only";
	size_t output_data_size    = 256;
	int result                 = 0;

	if( input_data_size > output_data_size )
	{
		libcerror_error_set(
		 &error,
		 LIBCERROR_ERROR_DOMAIN_ARGUMENTS,
		 LIBCERROR_ARGUMENT_ERROR_VALUE_OUT_OF_BOUNDS,
		 "%s: invalid input data size value out of bounds.",
		 function );

		goto on_error;
	}
	result = libcaes_context_initialize(
	          &context,
	          &error );

	CAES_TEST_ASSERT_EQUAL_INT(
	 "result",
	 result,
	 1 );

	CAES_TEST_ASSERT_IS_NOT_NULL(
	 "context",
	 context );

	CAES_TEST_ASSERT_IS_NULL(
	 "error",
	 error );

        /* Note that the key must be set in encryption mode (LIBCAES_CRYPT_MODE_ENCRYPT)
         * for both decryption and encryption.
	 */
	result = libcaes_context_set_key(
	          context,
	          LIBCAES_CRYPT_MODE_ENCRYPT,
	          key,
	          key_bit_size,
	          &error );

	CAES_TEST_ASSERT_EQUAL_INT(
	 "result",
	 result,
	 1 );

	CAES_TEST_ASSERT_IS_NULL(
	 "error",
	 error );

	result = libcaes_crypt_ccm_ctr_only(
	          context,
	          mode,
	          nonce,
	          nonce_size,
	          input_data,
	          input_data_size,
	          output_data,
	          output_data_size,
	          &error );

	CAES_TEST_ASSERT_EQUAL_INT(
	 "result",
	 result,
	 1 );

	CAES_TEST_ASSERT_IS_NULL(
	 "error",
	 error );

	result = memory_compare(
	          output_data,
	          expected_output_data,
	          expected_output_data_size );

	CAES_TEST_ASSERT_EQUAL_INT(
	 "result",
	 result,
	 0 );

	result = libcaes_context_free(
	          &context,
	          &error );

	CAES_TEST_ASSERT_EQUAL_INT(
	 "result",
	 result,
	 1 );

	CAES_TEST_ASSERT_IS_NULL(
	 "context",
	 context );

	CAES_TEST_ASSERT_IS_NULL(
	 "error",
	 error );

	return( 1 );

on_error:
	if( error != NULL )
	{
		libcerror_error_free(
		 &error );
	}
	if( context != NULL )
	{
		libcaes_context_free(
		 &context,
		 NULL );
	}
	return( -1 );
}

/* Tests AES-CCM decryption
 * Returns 1 if successful or -1 on error
 */
int caes_test_crypt_ccm_decryption(
     void )
{
	caes_test_vector_t *test_vector = NULL;
	int result                      = 0;
	int test_index                  = 0;

	for( test_index = 0;
	     test_index < 1;
	     test_index++ )
	{
		test_vector = &( caes_crypt_ccm_test_vectors[ test_index ] );

		result = caes_test_crypt_ccm_ctr_only(
		          LIBCAES_CRYPT_MODE_DECRYPT,
		          test_vector->key_data,
		          128,
		          test_vector->nonce,
		          13,
		          test_vector->cipher_text,
		          test_vector->text_size,
		          test_vector->plain_text,
		          test_vector->text_size );

		CAES_TEST_ASSERT_EQUAL_INT(
		 "result",
		 result,
		 1 );
	}
	return( 1 );

on_error:
	return( -1 );
}

